import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { URL } from 'node:url';
import process from 'node:process';
const project = new URL('../', import.meta.url);
const destination = process.argv[2];
if (!destination) throw new Error('Supply the app Resources directory');
let html = await readFile(new URL('dist/index.html', project), 'utf8');
const scriptPath = html.match(/<script[^>]*src="([^"]+)"[^>]*><\/script>/)?.[1];
const stylePath = html.match(/<link[^>]*href="([^"]+\.css)"[^>]*>/)?.[1];
if (!scriptPath || !stylePath) throw new Error('Missing desktop build output');
const script = await readFile(new URL('dist/' + scriptPath.replace(/^\.\//, ''), project), 'utf8');
const style = await readFile(new URL('dist/' + stylePath.replace(/^\.\//, ''), project), 'utf8');
html = html.replace(/<script[^>]*src="[^"]+"[^>]*><\/script>/, () => '<script type="module">' + script.replace(/<\/script/gi, '<\\/script') + '</script>');
html = html.replace(/<link[^>]*href="[^"]+\.css"[^>]*>/, () => '<style>' + style + '</style>');
html = html.replace("connect-src 'self' ws://127.0.0.1:*", "connect-src 'none'");
await mkdir(destination, { recursive: true });
const notices = await readFile(new URL('THIRD_PARTY_NOTICES.md', project), 'utf8');
html = html.replace('<head>', '<head>\n<!--\n' + notices.replace(/--/g, '—') + '\n-->');
await writeFile(destination + '/desktop.html', html);
